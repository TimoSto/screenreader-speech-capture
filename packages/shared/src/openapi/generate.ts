// Generates docs/usage/openapi.yaml (`pnpm openapi`): the endpoints and prose from `spec.ts`, the
// `components.schemas` from the valibot schemas in `../schemas.ts`.
import { toJsonSchemaDefs } from '@valibot/to-json-schema';
import path from 'node:path';
import { stringify } from 'yaml';
import { API_SCHEMAS } from '../schemas.js';
import { INFO, OPENAPI_VERSION, PARAMETERS, PATHS, RESPONSES, SERVERS, TAGS } from './spec.js';

export const OPENAPI_FILE = path.resolve(
  import.meta.dirname,
  '../../../../docs/usage/openapi.yaml',
);

/** The JSON Schemas of the API, by name, with `$ref`s pointing into `components.schemas`. */
export function componentSchemas(): Record<string, unknown> {
  return toJsonSchemaDefs(API_SCHEMAS, {
    target: 'draft-2020-12',
    // Rules JSON Schema can't express (trimmed length, TextDecoder labels) stay in the prose.
    ignoreActions: ['check'],
    overrideRef: ({ referenceId }) => `#/components/schemas/${referenceId}`,
  });
}

/** The whole OpenAPI document. */
export function openApiDocument(): Record<string, unknown> {
  return {
    openapi: OPENAPI_VERSION,
    info: INFO,
    servers: SERVERS,
    tags: TAGS,
    paths: PATHS,
    components: { parameters: PARAMETERS, responses: RESPONSES, schemas: componentSchemas() },
  };
}

/** The file's content (Prettier formats it after). */
export function openApiYaml(): string {
  return `# Generated by \`pnpm openapi\` from packages/shared/src/openapi. Do not edit by hand.\n${stringify(
    openApiDocument(),
    {
      lineWidth: 0,
      // Quotes strings such as timestamps that YAML 1.1 tools would read as dates.
      schema: 'yaml-1.1',
      // No `&anchors`: the converter reuses objects, the file should stay plain.
      aliasDuplicateObjects: false,
    },
  )}`;
}
